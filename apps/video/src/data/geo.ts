import geoJson from './geo.json';

export type Slide = {
  readonly x: number;
  readonly y: number;
  readonly areaHa: number;
  readonly km: number;
  readonly eviBefore: number;
  readonly eviAfter: number;
};

type GeoData = {
  readonly width: number;
  readonly height: number;
  readonly proj: {
    readonly west: number;
    readonly north: number;
    readonly sx: number;
    readonly sy: number;
  };
  readonly epicentre: [number, number];
  readonly provinces: {readonly name: string; readonly areaKm2: number; readonly d: string}[];
  readonly slides: Slide[];
  readonly stats: {
    readonly count: number;
    readonly totalHa: number;
    readonly meanEviBefore: number;
    readonly meanEviAfter: number;
  };
};

// Generated by scripts/build-geo.mjs from apps/web/public/data/*.geojson.
export const GEO = geoJson as GeoData;

/** Project lon/lat into the map's SVG viewBox coordinates. */
export const toMap = (lon: number, lat: number): [number, number] => [
  (lon - GEO.proj.west) * GEO.proj.sx,
  (GEO.proj.north - lat) * GEO.proj.sy,
];

export const MAP_VIEWBOX = `0 0 ${GEO.width} ${GEO.height}`;

/** Dot radius in viewBox units, scaled by landslide area. */
export const slideRadius = (areaHa: number) => 2.6 + Math.sqrt(areaHa) * 2.6;
